'use client';

import * as React from 'react';
import * as DropdownMenu from '@radix-ui/react-dropdown-menu';
import { toPng, toSvg } from 'html-to-image';
import { jsPDF } from 'jspdf';
import { Check, Download, Loader2 } from 'lucide-react';
import { toast } from 'sonner';
import type { AnalysisResult, GraphKind } from '@/lib/core/types';
import { Button } from '@/components/ui/button';
import { cn } from '@/lib/utils';

/**
 * Export.
 *
 * SVG, PNG and PDF are produced in the browser from the live canvas, because
 * the rendered geometry already exists there — reproducing layout headlessly on
 * the server would be a second implementation to keep in sync. JSON and Mermaid
 * come from the server, where they are pure data transforms.
 */

export interface ExportMenuProps {
  result: AnalysisResult;
  graph: GraphKind;
  /** Returns the live React Flow viewport element to rasterise. */
  getCanvasElement: () => HTMLElement | null;
}

type Format = 'svg' | 'png' | 'pdf' | 'json' | 'json-graph' | 'mermaid' | 'markdown';

const FORMATS: { id: Format; label: string; detail: string; group: 'image' | 'data' }[] = [
  { id: 'svg', label: 'SVG', detail: 'Vector, current view', group: 'image' },
  { id: 'png', label: 'PNG', detail: '2× raster, current view', group: 'image' },
  { id: 'pdf', label: 'PDF', detail: 'Single page, landscape', group: 'image' },
  { id: 'mermaid', label: 'Mermaid', detail: 'Current view as .mmd', group: 'data' },
  { id: 'markdown', label: 'Markdown', detail: 'All views, one document', group: 'data' },
  { id: 'json-graph', label: 'Graph JSON', detail: 'Nodes and edges of this view', group: 'data' },
  { id: 'json', label: 'Full analysis JSON', detail: 'Everything, for tooling', group: 'data' },
];

export function ExportMenu({ result, graph, getCanvasElement }: ExportMenuProps) {
  const [busy, setBusy] = React.useState<Format | null>(null);
  const [done, setDone] = React.useState<Format | null>(null);

  const stem = `${result.repo.name.replace(/[^A-Za-z0-9._-]/g, '-')}-${graph}`;

  const download = (blobOrUrl: Blob | string, filename: string) => {
    const url = typeof blobOrUrl === 'string' ? blobOrUrl : URL.createObjectURL(blobOrUrl);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = filename;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    if (typeof blobOrUrl !== 'string') URL.revokeObjectURL(url);
  };

  const run = async (format: Format) => {
    setBusy(format);
    setDone(null);
    try {
      if (format === 'svg' || format === 'png' || format === 'pdf') {
        const element = getCanvasElement();
        if (!element) throw new Error('The graph canvas is not ready yet.');

        // html-to-image inlines computed styles; the background must be set
        // explicitly or the export comes out transparent-on-white.
        const options = {
          backgroundColor: '#08080c',
          pixelRatio: format === 'png' ? 2 : 1,
          cacheBust: true,
          filter: (node: HTMLElement) => {
            const className = typeof node.className === 'string' ? node.className : '';
            // Controls and the minimap are chrome, not diagram.
            return (
              !className.includes('react-flow__controls') &&
              !className.includes('react-flow__minimap')
            );
          },
        };

        if (format === 'svg') {
          download(await toSvg(element, options), `${stem}.svg`);
        } else {
          const dataUrl = await toPng(element, options);
          if (format === 'png') {
            download(dataUrl, `${stem}.png`);
          } else {
            const { width, height } = element.getBoundingClientRect();
            const landscape = width >= height;
            const pdf = new jsPDF({
              orientation: landscape ? 'landscape' : 'portrait',
              unit: 'pt',
              format: [width, height],
            });
            pdf.addImage(dataUrl, 'PNG', 0, 0, width, height);
            pdf.setFontSize(9);
            pdf.setTextColor(150);
            pdf.text(`${result.repo.name} · ${graph} · generated by DevGraph`, 12, height - 10);
            pdf.save(`${stem}.pdf`);
          }
        }
      } else {
        const params = new URLSearchParams();
        if (format === 'json') params.set('format', 'json');
        else if (format === 'json-graph') {
          params.set('format', 'json');
          params.set('graph', graph);
        } else if (format === 'mermaid') {
          params.set('format', 'mermaid');
          params.set('graph', graph);
        } else {
          params.set('format', 'markdown');
        }

        const response = await fetch(`/api/analyses/${result.id}/export?${params}`);
        if (!response.ok) {
          const body = await response.json().catch(() => null);
          throw new Error(body?.error?.message ?? `Export failed with ${response.status}`);
        }
        const extension = format === 'mermaid' ? 'mmd' : format === 'markdown' ? 'md' : 'json';
        download(await response.blob(), `${stem}.${extension}`);
      }

      setDone(format);
      window.setTimeout(() => setDone(null), 2000);
    } catch (error) {
      toast.error(error instanceof Error ? error.message : 'Export failed.');
    } finally {
      setBusy(null);
    }
  };

  return (
    <DropdownMenu.Root>
      <DropdownMenu.Trigger asChild>
        <Button variant="outline" size="sm">
          <Download />
          Export
        </Button>
      </DropdownMenu.Trigger>
      <DropdownMenu.Portal>
        <DropdownMenu.Content
          align="end"
          sideOffset={6}
          className={cn(
            'glass z-100 w-64 rounded-lg p-1.5',
            'data-[state=open]:animate-in data-[state=open]:fade-in-0 data-[state=open]:zoom-in-95',
          )}
        >
          {(['image', 'data'] as const).map((group, index) => (
            <React.Fragment key={group}>
              {index > 0 ? <DropdownMenu.Separator className="bg-line my-1.5 h-px" /> : null}
              <DropdownMenu.Label className="text-ink-ghost px-2 py-1 text-[10px] font-semibold tracking-[0.14em] uppercase">
                {group === 'image' ? 'Current view' : 'Data'}
              </DropdownMenu.Label>
              {FORMATS.filter((format) => format.group === group).map((format) => (
                <DropdownMenu.Item
                  key={format.id}
                  disabled={busy !== null}
                  onSelect={(event) => {
                    event.preventDefault();
                    void run(format.id);
                  }}
                  className="text-ink-muted data-[highlighted]:bg-hover data-[highlighted]:text-ink flex cursor-pointer items-center gap-2.5 rounded-sm px-2 py-1.5 text-[12.5px] outline-none"
                >
                  <span className="flex size-3.5 shrink-0 items-center justify-center">
                    {busy === format.id ? (
                      <Loader2 className="text-edge size-3 animate-spin" />
                    ) : done === format.id ? (
                      <Check className="text-stable size-3" />
                    ) : null}
                  </span>
                  <span className="flex-1">{format.label}</span>
                  <span className="text-ink-ghost text-[10.5px]">{format.detail}</span>
                </DropdownMenu.Item>
              ))}
            </React.Fragment>
          ))}
        </DropdownMenu.Content>
      </DropdownMenu.Portal>
    </DropdownMenu.Root>
  );
}
