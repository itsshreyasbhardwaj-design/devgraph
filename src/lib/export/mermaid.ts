import type { AnalysisResult, DevGraphView, GraphKind, GraphNode } from '@/lib/core/types';
import { basename } from '@/lib/core/paths';

/**
 * Mermaid export.
 *
 * Each graph kind maps to the Mermaid diagram type that actually suits it —
 * `classDiagram` for types, `erDiagram` for the schema, flowcharts for
 * everything else — rather than forcing every view through one generic shape.
 */

export interface MermaidOptions {
  /** Cap on emitted nodes; Mermaid's renderer degrades badly past a few hundred. */
  maxNodes: number;
  direction: 'TD' | 'LR';
  includeMetrics: boolean;
}

export const DEFAULT_MERMAID_OPTIONS: MermaidOptions = {
  maxNodes: 160,
  direction: 'LR',
  includeMetrics: false,
};

/** Mermaid ids must be alphanumeric-ish and stable across runs. */
function safeId(raw: string): string {
  const cleaned = raw
    .replace(/[^A-Za-z0-9]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '');
  return cleaned ? `n_${cleaned}`.slice(0, 60) : `n_${hash(raw)}`;
}

function hash(text: string): string {
  let value = 0x811c9dc5;
  for (let i = 0; i < text.length; i += 1) {
    value ^= text.charCodeAt(i);
    value = Math.imul(value, 0x01000193) >>> 0;
  }
  return value.toString(36);
}

function escapeLabel(label: string): string {
  return label.replace(/"/g, '&quot;').replace(/[<>]/g, (char) => (char === '<' ? '&lt;' : '&gt;'));
}

/** Trim a view down to the highest-degree nodes plus their edges. */
function limitView(
  view: DevGraphView,
  maxNodes: number,
): { nodes: GraphNode[]; edges: DevGraphView['edges'] } {
  if (view.nodes.length <= maxNodes) return { nodes: view.nodes, edges: view.edges };

  const degree = new Map<string, number>();
  for (const edge of view.edges) {
    degree.set(edge.source, (degree.get(edge.source) ?? 0) + 1);
    degree.set(edge.target, (degree.get(edge.target) ?? 0) + 1);
  }
  const nodes = [...view.nodes]
    .sort(
      (a, b) =>
        (degree.get(b.id) ?? 0) - (degree.get(a.id) ?? 0) || (b.weight ?? 0) - (a.weight ?? 0),
    )
    .slice(0, maxNodes);
  const ids = new Set(nodes.map((n) => n.id));
  return { nodes, edges: view.edges.filter((e) => ids.has(e.source) && ids.has(e.target)) };
}

export function toMermaid(view: DevGraphView, options: Partial<MermaidOptions> = {}): string {
  const config = { ...DEFAULT_MERMAID_OPTIONS, ...options };

  switch (view.kind) {
    case 'classes':
      return classDiagram(view, config);
    case 'schema':
      return erDiagram(view, config);
    default:
      return flowchart(view, config);
  }
}

function flowchart(view: DevGraphView, options: MermaidOptions): string {
  const { nodes, edges } = limitView(view, options.maxNodes);
  const direction = view.layout === 'tree' ? 'TD' : options.direction;
  const lines = [`%% ${view.title} — generated by DevGraph`, `flowchart ${direction}`];

  const shapeFor = (node: GraphNode): [string, string] => {
    switch (node.kind) {
      case 'folder':
        return ['[/', '/]'];
      case 'external':
      case 'package':
        return ['([', '])'];
      case 'route':
        return ['>', ']'];
      case 'env':
        return ['{{', '}}'];
      case 'entry':
        return ['((', '))'];
      case 'table':
        return ['[(', ')]'];
      default:
        return ['[', ']'];
    }
  };

  for (const node of nodes) {
    const [open, close] = shapeFor(node);
    const metrics =
      options.includeMetrics && node.metrics?.loc
        ? `<br/><small>${node.metrics.loc} LOC</small>`
        : '';
    lines.push(`  ${safeId(node.id)}${open}"${escapeLabel(node.label)}${metrics}"${close}`);
  }

  for (const edge of edges) {
    const arrow = edge.cyclic ? '-.->' : edge.kind === 'contains' ? '---' : '-->';
    const label = edge.label ? `|${escapeLabel(edge.label)}|` : '';
    lines.push(`  ${safeId(edge.source)} ${arrow}${label} ${safeId(edge.target)}`);
  }

  const cyclic = edges.filter((edge) => edge.cyclic);
  if (cyclic.length) {
    lines.push(
      `  linkStyle ${edges
        .map((e, i) => (e.cyclic ? i : -1))
        .filter((i) => i >= 0)
        .join(',')} stroke:#ef4444,stroke-width:2px`,
    );
  }

  if (view.nodes.length > nodes.length) {
    lines.push(`  %% ${view.nodes.length - nodes.length} further nodes omitted for readability`);
  }

  return lines.join('\n');
}

function classDiagram(view: DevGraphView, options: MermaidOptions): string {
  const { nodes, edges } = limitView(view, Math.min(options.maxNodes, 80));
  const lines = [`%% ${view.title} — generated by DevGraph`, 'classDiagram'];

  for (const node of nodes) {
    const id = safeId(node.label);
    const methods = (node.meta?.methods as string[] | undefined) ?? [];
    const fields = (node.meta?.fields as string[] | undefined) ?? [];

    if (!methods.length && !fields.length) {
      lines.push(`  class ${id}`);
    } else {
      lines.push(`  class ${id} {`);
      for (const field of fields.slice(0, 10)) lines.push(`    +${field}`);
      for (const method of methods.slice(0, 14)) lines.push(`    ${method}`);
      lines.push('  }');
    }

    if (node.kind === 'interface') lines.push(`  <<interface>> ${id}`);
    else if (node.kind === 'enum') lines.push(`  <<enumeration>> ${id}`);
    else if (node.meta?.isAbstract) lines.push(`  <<abstract>> ${id}`);
  }

  const byId = new Map(nodes.map((n) => [n.id, n.label]));
  for (const edge of edges) {
    const source = byId.get(edge.source);
    const target = byId.get(edge.target);
    if (!source || !target) continue;
    // Mermaid draws inheritance from child to parent.
    const arrow = edge.kind === 'implements' ? '..|>' : '--|>';
    lines.push(`  ${safeId(source)} ${arrow} ${safeId(target)}`);
  }

  return lines.join('\n');
}

function erDiagram(view: DevGraphView, options: MermaidOptions): string {
  const { nodes, edges } = limitView(view, Math.min(options.maxNodes, 60));
  const lines = [`%% ${view.title} — generated by DevGraph`, 'erDiagram'];
  const byId = new Map(nodes.map((n) => [n.id, n.label]));

  for (const edge of edges) {
    const source = byId.get(edge.source);
    const target = byId.get(edge.target);
    if (!source || !target) continue;
    lines.push(
      `  ${safeId(source)} }o--|| ${safeId(target)} : "${escapeLabel(edge.label ?? 'references')}"`,
    );
  }

  for (const node of nodes) {
    const columns = (node.meta?.columns as string[] | undefined) ?? [];
    if (!columns.length) {
      lines.push(`  ${safeId(node.label)} {`, '  }');
      continue;
    }
    lines.push(`  ${safeId(node.label)} {`);
    for (const column of columns.slice(0, 20)) {
      // Column entries look like `🔑 id: String`.
      const cleaned = column.replace(/^🔑\s*/, '');
      const [name, type = 'unknown'] = cleaned.split(':').map((part) => part.trim());
      const key = column.startsWith('🔑') ? ' PK' : '';
      lines.push(`    ${sanitizeType(type)} ${sanitizeName(name)}${key}`);
    }
    lines.push('  }');
  }

  return lines.join('\n');
}

function sanitizeName(name: string): string {
  return name.replace(/[^A-Za-z0-9_]/g, '_') || 'column';
}

function sanitizeType(type: string): string {
  return type.replace(/[^A-Za-z0-9_]/g, '') || 'string';
}

/** A single document containing every view, useful for docs and PR reviews. */
export function analysisToMermaid(result: AnalysisResult, kinds?: GraphKind[]): string {
  const selected = kinds ?? (Object.keys(result.graphs) as GraphKind[]);
  const blocks: string[] = [
    `# ${result.repo.name} — architecture diagrams`,
    '',
    `Generated by DevGraph on ${new Date(result.createdAt).toISOString().slice(0, 10)}.`,
    '',
  ];

  for (const kind of selected) {
    const view = result.graphs[kind];
    if (!view || !view.nodes.length) continue;
    blocks.push(
      `## ${view.title}`,
      '',
      view.description,
      '',
      '```mermaid',
      toMermaid(view),
      '```',
      '',
    );
  }

  return blocks.join('\n');
}

/** Filename stem for downloads. */
export function exportBasename(result: AnalysisResult, kind?: GraphKind): string {
  const repo = basename(result.repo.name).replace(/[^A-Za-z0-9._-]/g, '-');
  return kind ? `${repo}-${kind}` : `${repo}-architecture`;
}
